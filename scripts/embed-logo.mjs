#!/usr/bin/env node
// Embeds the official logo into src/lib/commerce/brand-logo.ts (used by the PDF receipt and email).
// Usage: node scripts/embed-logo.mjs path/to/logo.png   (PNG or JPEG, ideally ≥ 512 px wide, ≤ 1 MB)
import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/embed-logo.mjs <logo.png|logo.jpg>");
  process.exit(1);
}
const buf = readFileSync(file);
const mime = buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) ? "image/png" : buf[0] === 0xff && buf[1] === 0xd8 ? "image/jpeg" : null;
if (!mime) throw new Error("The logo must be a PNG or JPEG file.");
if (buf.length > 1024 * 1024) throw new Error(`The logo is ${(buf.length / 1048576).toFixed(1)} MB; please use a version under 1 MB.`);
writeFileSync(
  "src/lib/commerce/brand-logo.ts",
  `/**
 * The official CRAFT & CODE logo, embedded for the PDF receipt and the email header.
 * Generated by \`node scripts/embed-logo.mjs\` from ${file.split(/[\\/]/).pop()} (${buf.length} bytes). Do not edit by hand.
 */
export const BRAND_LOGO: { mime: "image/png" | "image/jpeg"; base64: string } | null = { mime: "${mime}", base64: "${buf.toString("base64")}" };
`,
);
console.log(`Embedded ${mime} logo (${buf.length} bytes) into src/lib/commerce/brand-logo.ts`);
